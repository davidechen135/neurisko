"""Compare the Eurisko engine with hill-climbing at the same battle budget (R8.2).

Methods, per seed:
  engine        Neurisko, 20 generations, seed heuristics + code meta-heuristics (no LLM)
  engine+llm    the same with Invent on the endpoint from .env (only with --llm)
  hc            random-restart hill-climb on the fixed gauntlet
  hc+hof        the same, but every local optimum joins a hall of fame, scored like the engine

hc+hof isolates what the heuristics add beyond the hall-of-fame mechanism.

Final exam: every champion plays the held-out gauntlet plus all champions of all methods
(round robin), half weight each. Writes docs/BASELINE.md.

Run: uv run python scripts/compare_baseline.py [--seeds 5] [--generations 20] [--llm]
"""

from __future__ import annotations

import argparse
import random
import statistics
import time
from datetime import date
from pathlib import Path

from neurisko.engine.evolve import Evolution, EvolveConfig
from neurisko.engine.scoring import pool_score
from neurisko.games.autobattler import MonsterMash
from neurisko.runs.session import default_seed_rules

OUT = Path("docs/BASELINE.md")


def run_engine(seed: int, generations: int, llm=None) -> tuple[tuple, int]:
    game = MonsterMash()
    cfg = EvolveConfig(generations=generations, seed=seed)
    ev = Evolution(game, cfg, default_seed_rules(game), llm=llm)
    result = ev.run()
    return result.best, game.battles_run


def hill_climb(seed: int, budget: int, use_hof: bool, hof_cap: int = 12) -> tuple:
    game = MonsterMash()
    rng = random.Random(seed)
    hof: list[tuple] = []

    def value(d):
        return pool_score(game, d, hof, 0.5) if use_hof else game.score(d).score

    best, best_v = None, -1.0
    while game.battles_run < budget:
        d = game.random_design(rng)
        v = value(d)
        improved = True
        while improved and game.battles_run < budget:
            improved = False
            for n in game.mutations(d, rng):
                if game.battles_run >= budget:
                    break
                nv = value(n)
                if nv > v:
                    d, v, improved = n, nv, True
                    break
        if use_hof and d not in hof:
            hof.append(d)
            if len(hof) > hof_cap:
                hof.remove(min(hof, key=value))
        # Champion = best local optimum against the current pool.
        candidates = [x for x in (best, d) if x is not None]
        best = max(candidates, key=value)
        best_v = value(best)
    del best_v
    return best


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--generations", type=int, default=20)
    ap.add_argument("--llm", action="store_true")
    args = ap.parse_args()

    llm = None
    if args.llm:
        from neurisko.llm import OpenAICompatClient
        from neurisko.settings import Settings

        s = Settings()
        llm = OpenAICompatClient(
            s.llm_base_url, s.llm_model, s.llm_api_key.get_secret_value(), s.llm_timeout_s
        )

    methods = ["engine", *(["engine+llm"] if llm else []), "hc", "hc+hof"]
    champs: dict[tuple[str, int], tuple] = {}
    budgets: dict[int, int] = {}
    for seed in range(args.seeds):
        t = time.perf_counter()
        champs[("engine", seed)], budgets[seed] = run_engine(seed, args.generations)
        if llm:
            champs[("engine+llm", seed)], _ = run_engine(seed, args.generations, llm)
        champs[("hc", seed)] = hill_climb(seed, budgets[seed], use_hof=False)
        champs[("hc+hof", seed)] = hill_climb(seed, budgets[seed], use_hof=True)
        print(f"seed {seed}: budget {budgets[seed]:,} battles, {time.perf_counter() - t:.0f}s")
        for m in methods:
            print(f"  {m:<11} {list(champs[(m, seed)])}")

    held = MonsterMash().held_out()
    pool = list(dict.fromkeys(champs.values()))
    exam = {k: pool_score(held, d, pool, 0.5) for k, d in champs.items()}
    held_only = {k: held.score(d).score for k, d in champs.items()}

    rows = []
    for m in methods:
        vals = [exam[(m, s)] for s in range(args.seeds)]
        ho = [held_only[(m, s)] for s in range(args.seeds)]
        rows.append((m, statistics.mean(vals), min(vals), max(vals), statistics.mean(ho), vals))
    rows.sort(key=lambda r: r[1], reverse=True)

    lines = [
        "# Baseline comparison",
        "",
        f"Generated by `scripts/compare_baseline.py` on {date.today()}: {args.seeds} seeds, "
        f"{args.generations} generations, mean battle budget "
        f"{statistics.mean(budgets.values()):,.0f} per method per seed.",
        "",
        "**Final exam** = score against the held-out gauntlet plus every champion from every "
        "method (round robin), half weight each. **Held-out** = held-out gauntlet only "
        "(saturates near 1.0, shown for reference).",
        "",
        "| method | final exam mean | min | max | held-out mean | per seed |",
        "|---|---|---|---|---|---|",
    ]
    for m, mean, lo, hi, ho, vals in rows:
        per = ", ".join(f"{v:.3f}" for v in vals)
        lines.append(f"| {m} | **{mean:.3f}** | {lo:.3f} | {hi:.3f} | {ho:.3f} | {per} |")
    lines += ["", "## Champions", ""]
    for seed in range(args.seeds):
        for m in methods:
            lines.append(f"- seed {seed}, {m}: `{' > '.join(champs[(m, seed)])}`")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print("\n".join(lines[8 : 8 + len(rows) + 2]))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
